"""Integrated staff scheduling + commuter bus routing (IWSBR), and the sequential benchmark.

Integrated:  the paper's staff model (StaffSchedulingSolver, unchanged) plus a transport block in the
             same MIP. Commuting demand is generated by the staff variables (non-Saudi riders only).
             Transport cost replaces the trip-consolidation weight W_bus, so W_bus is set to 0.
Sequential:  solve the staff model alone (with the paper's W_bus), then solve the same transport block
             with that schedule's demand fixed. Both use the same transport model and cost function, so
             the difference between them is the value of integration.

Transport block (per period t, one route = one bus for that hour, as in the routing code):
  y[b,t]        branch b needs a bus stop at t (some rider starts or ends a shift there)
  lam[r,v,t]    route r is driven by vehicle type v at t
  n_own/n_extra buses of each (cluster, kind): own fleet up to what is available, extra buses rented
  drop[b,t] + pick[b,t] <= U_b * y[b,t]                (activation)
  sum_{r ∋ b, v} lam[r,v,t] = y[b,t]                    (each active stop on exactly one route)
  load on every leg of a selected route <= its capacity  (big-M, only where it can bind)
  sum_{r, v of a kind} lam[r,v,t] <= n_own + n_extra    (fleet, every hour)
"""
import io
import sys
import time
from contextlib import redirect_stdout
from dataclasses import dataclass, field

from docplex.mp.model import Model

from instance import RENTAL_FACTOR, WEEK_HOURS, Instance
from solver_cplex_new import StaffSchedulingSolver  # staff_scheduling (path set up by instance.py)
from fix_sensitive_analyze import BASE_PARAMS, Route as CodeRoute  # bus_scheduling_routing: the paper's route evaluation


def shift_events(staff):
    """hour -> shift ids starting / ending at that hour (same convention as the staff model)."""
    starts = {t: [] for t in range(WEEK_HOURS)}
    ends = {t: [] for t in range(WEEK_HOURS)}
    for s in staff.shifts:
        starts[s["start"] % WEEK_HOURS].append(s["id"])
        ends[s["end"] % WEEK_HOURS].append(s["id"])
    return starts, ends


@dataclass
class TransportBlock:
    y: dict = field(default_factory=dict)
    lam: dict = field(default_factory=dict)
    n_own: dict = field(default_factory=dict)
    n_extra: dict = field(default_factory=dict)
    route_cost: object = 0  # distance + driving time
    timing_cost: object = 0  # early/late arrival penalty (fixed-schedule routing only)
    fleet_cost: object = 0
    timing_fn: object = None


def route_timing_costs(inst: Instance, drop, pick):
    """(route, t) -> the paper's early/late arrival penalty for a fixed schedule.

    Uses the routing code's own Route.evaluate_time_feasibility (best departure shift, dwell time
    from the actual passenger counts), so the cost is identical to the paper's route evaluation.
    """
    demand_data = {(t, b): {"board": pick[b, t], "alight": drop[b, t]} for (b, t) in drop}
    cache = {}

    def cost(route, t):
        key = (route.rid, t)
        if key not in cache:
            r = CodeRoute(route.rid, list(route.stops), inst.distance_matrix, t, route.acc, BASE_PARAMS)
            r.evaluate_time_feasibility(demand_data, inst.distance_matrix)
            cache[key] = r.time_cost
        return cache[key]

    return cost


def add_transport(mdl, inst: Instance, drop, pick, fixed_demand=False, timing_ref=None):
    """Add the transport block. drop/pick map (b, t) -> expression (integrated) or int (fixed demand).

    With fixed demand the exact timing penalty is added to every route's cost. In the integrated
    model it is left out: it depends on passenger counts through dwell time (nonlinear), and since it
    is never negative, leaving it out makes the integrated model a relaxation (its bound is a valid
    lower bound for the full problem).
    """
    tb = TransportBlock()
    timing = route_timing_costs(inst, drop, pick) if fixed_demand else None
    if timing_ref is not None and not fixed_demand:
        # Heuristic timing estimate for the integrated model (not a bound): each route's timing penalty at
        # reference passenger counts (e.g. the current schedule's); a stop inactive in the reference is costed
        # as one drop-off and one pick-up, which is deliberately pessimistic.
        ref_drop = {k: (v[0] if sum(v) > 0 else 1) for k, v in timing_ref.items()}
        ref_pick = {k: (v[1] if sum(v) > 0 else 1) for k, v in timing_ref.items()}
        timing = route_timing_costs(inst, ref_drop, ref_pick)
    tb.timing_fn = timing
    rider_branches = [b for b in inst.branches if inst.riders_by_branch[b]]
    cap_ub = {b: len(inst.riders_by_branch[b]) for b in rider_branches}

    active = {}
    for b in rider_branches:
        for t in range(WEEK_HOURS):
            if fixed_demand:
                if drop[b, t] + pick[b, t] > 0:
                    active[b, t] = 1
            else:
                tb.y[b, t] = mdl.binary_var(name=f"y_{b}_{t}")
                active[b, t] = tb.y[b, t]
                mdl.add_constraint(drop[b, t] + pick[b, t] <= cap_ub[b] * tb.y[b, t], ctname=f"act_{b}_{t}")

    def leg_loads(route, t):
        m = len(route.stops)
        return [sum(drop[route.stops[k], t] for k in range(l, m)) + sum(pick[route.stops[k], t] for k in range(l))
                for l in range(m + 1)]

    cover = {key: [] for key in active}
    fleet_terms = {}
    for r in inst.routes:
        vtypes = inst.vehicle_types_for(r)
        u_r = sum(cap_ub[b] for b in r.stops)
        for t in range(WEEK_HOURS):
            if any((b, t) not in active for b in r.stops):
                continue  # with fixed demand, a route may only visit active stops
            if fixed_demand:
                loads = leg_loads(r, t)
                vs = [v for v in vtypes if max(loads) <= inst.vehicles[v].capacity]
            else:
                vs = vtypes
            lam_rt = []
            for v in vs:
                var = mdl.binary_var(name=f"lam_{r.rid}_{inst.vehicles[v].cluster[:8]}_{inst.vehicles[v].kind.split()[0]}_{t}")
                tb.lam[r.rid, v, t] = var
                lam_rt.append((v, var))
                for b in r.stops:
                    cover[b, t].append(var)
                fleet_terms.setdefault((v, t), []).append(var)
            if not fixed_demand:
                tight = [(v, var) for v, var in lam_rt if inst.vehicles[v].capacity < u_r]
                if tight:  # load <= U_r - sum_v (U_r - Cap_v) lam_v   (binds only for the chosen vehicle)
                    rhs = u_r - mdl.sum((u_r - inst.vehicles[v].capacity) * var for v, var in tight)
                    for l, load in enumerate(leg_loads(r, t)):
                        mdl.add_constraint(load <= rhs, ctname=f"cap_{r.rid}_{t}_{l}")

    for (b, t), terms in cover.items():
        if not terms and fixed_demand:
            raise ValueError(f"No feasible route for stop {(b, t)}")
        mdl.add_constraint(mdl.sum(terms) == active[b, t], ctname=f"cov_{b}_{t}")

    vname = {key: f"{v.cluster[:8]}_{v.kind.split()[0]}" for key, v in inst.vehicles.items()}
    for key, v in inst.vehicles.items():
        tb.n_own[key] = mdl.integer_var(lb=0, ub=v.available, name=f"own_{vname[key]}")
        tb.n_extra[key] = mdl.integer_var(lb=0, name=f"extra_{vname[key]}")
    for (v, t), terms in fleet_terms.items():
        mdl.add_constraint(mdl.sum(terms) <= tb.n_own[v] + tb.n_extra[v], ctname=f"fleet_{vname[v]}_{t}")

    route_by_id = {r.rid: r for r in inst.routes}
    tb.route_cost = mdl.sum(inst.route_cost(route_by_id[rid], v) * var for (rid, v, t), var in tb.lam.items())
    if timing is not None:
        tb.timing_cost = mdl.sum(timing(route_by_id[rid], t) * var for (rid, v, t), var in tb.lam.items())
    tb.fleet_cost = mdl.sum(inst.vehicles[k].weekly_fixed * (tb.n_own[k] + RENTAL_FACTOR * tb.n_extra[k])
                            for k in inst.vehicles)
    return tb


def _solve(mdl, time_limit, mip_gap, log_path=None, threads=0):
    mdl.set_time_limit(time_limit)
    mdl.parameters.mip.tolerances.mipgap = mip_gap
    if threads:
        mdl.parameters.threads = threads
    buf = io.StringIO()
    t0 = time.time()
    with redirect_stdout(buf):
        sol = mdl.solve(log_output=True)
    elapsed = time.time() - t0
    if log_path:
        with open(log_path, "w", encoding="utf-8") as f:
            f.write(buf.getvalue())
    det = mdl.solve_details
    return sol, {"seconds": elapsed, "status": det.status, "best_bound": det.best_bound,
                 "mip_gap": det.mip_relative_gap, "nodes": det.nb_nodes_processed}


def _staff_parts(solver, sol):
    """Staff-side cost split, independent of the W_bus term."""
    kpi = solver.get_kpi_summary()
    bus_requests = sum(sol.get_value(v) for v in solver.b_start.values()) + \
        sum(sol.get_value(v) for v in solver.b_end.values())
    return kpi, bus_requests


def _schedule_demand(inst, x_on):
    starts, ends = shift_events(inst.staff)
    drop, pick = {}, {}
    for b in inst.branches:
        riders = set(inst.riders_by_branch[b])
        for t in range(WEEK_HOURS):
            drop[b, t] = sum(1 for s in starts[t] for i in riders if (i, s) in x_on)
            pick[b, t] = sum(1 for s in ends[t] for i in riders if (i, s) in x_on)
    return drop, pick


def route_given_schedule(inst, x_on, time_limit, mip_gap, log_path=None, threads=0):
    """Exact routing (all routes, exact timing penalty, fleet) for a fixed staff schedule.
    Solved with a zero gap (the mip_gap argument is ignored) so its cost is a proper upper-bound component;
    returns (None, info) if no solution is found within the time limit."""
    mip_gap = 0.0
    drop, pick = _schedule_demand(inst, x_on)
    mdl = Model(name="routing_given_schedule")
    tb = add_transport(mdl, inst, drop, pick, fixed_demand=True)
    mdl.minimize(tb.route_cost + tb.timing_cost + tb.fleet_cost)
    sol, info = _solve(mdl, time_limit, mip_gap, log_path, threads)
    if not sol:
        return None, info
    res = {"route_cost": sol.get_value(tb.route_cost), "timing_cost": sol.get_value(tb.timing_cost),
           "fleet_cost": sol.get_value(tb.fleet_cost),
           "buses": sum(sol.get_value(v) for v in list(tb.n_own.values()) + list(tb.n_extra.values())),
           "extra_buses": sum(sol.get_value(v) for v in tb.n_extra.values()),
           "stops": sum(1 for k in drop if drop[k] + pick[k] > 0),
           "riders_moved": sum(drop.values()) + sum(pick.values())}
    res["transport_cost"] = res["route_cost"] + res["timing_cost"] + res["fleet_cost"]
    route_by_id = {r.rid: r for r in inst.routes}
    rows = []
    for (rid, v, t), var in tb.lam.items():
        if sol.get_value(var) < 0.5:
            continue
        r, vt = route_by_id[rid], inst.vehicles[v]
        rows.append({"time": t, "route_id": rid, "stops": list(r.stops), "depot_id": r.acc, "cluster": vt.cluster,
                     "vehicle_type": v, "bus_kind": vt.kind, "capacity": vt.capacity, "distance": r.distance_km,
                     "travel_minutes": r.travel_min, "distance_cost": vt.per_km * r.distance_km,
                     "vehicle_time_cost": vt.per_min * r.travel_min, "service_penalty_cost": tb.timing_fn(r, t),
                     "board_by_stop": {b: pick[b, t] for b in r.stops},
                     "alight_by_stop": {b: drop[b, t] for b in r.stops}})
    res["selected_routes"] = rows
    return res, info


def staff_value_of(inst, args, x_on, threads=0):
    """Staff objective f(x) (no W_bus term) and KPIs of a given schedule: the staff model with x fixed."""
    args.w_bus_trip = 0.0
    solver = StaffSchedulingSolver(args, inst.staff)
    with redirect_stdout(io.StringIO()):
        solver.build_model()
    for (i, s), var in solver.x.items():
        var.lb = var.ub = 1 if (i, s) in x_on else 0
    sol, _ = _solve(solver.mdl, 600, 1e-6, None, threads)
    solver.solution = sol
    kpi, _ = _staff_parts(solver, sol)
    return sol.objective_value, kpi


def _log(log_path, suffix):
    return log_path and log_path.replace(".log", f"_{suffix}.log")


def solve_integrated(inst, args, time_limit=3600, mip_gap=1e-4, log_path=None, threads=0):
    """Integrated MIP (no timing term), then exact routing with timing for its schedule.

    Reported: lower_bound = the MIP's best bound, a valid lower bound on the full problem (timing >= 0);
    objective = staff cost + exact transport cost of the final solution; certified_gap between them.
    """
    args.w_bus_trip = 0.0  # transport is priced explicitly
    solver = StaffSchedulingSolver(args, inst.staff)
    with redirect_stdout(io.StringIO()):
        solver.build_model()
    mdl = solver.mdl
    staff_obj = mdl.objective_expr
    starts, ends = shift_events(inst.staff)
    drop, pick = {}, {}
    for b in inst.branches:
        riders = inst.riders_by_branch[b]
        for t in range(WEEK_HOURS):
            drop[b, t] = mdl.sum(solver.x[i, s] for i in riders for s in starts[t])
            pick[b, t] = mdl.sum(solver.x[i, s] for i in riders for s in ends[t])
    tb = add_transport(mdl, inst, drop, pick, fixed_demand=False)
    mdl.minimize(staff_obj + tb.route_cost + tb.fleet_cost)
    out = {"method": "integrated", "vars": mdl.number_of_variables, "binaries": mdl.number_of_binary_variables,
           "constraints": mdl.number_of_constraints}
    sol, info = _solve(mdl, time_limit, mip_gap, _log(log_path, "mip"), threads)
    out.update(status=info["status"], mip_seconds=info["seconds"], mip_gap=info["mip_gap"],
               nodes=info["nodes"], lower_bound=info["best_bound"])
    if not sol:
        return out
    solver.solution = sol
    kpi, _ = _staff_parts(solver, sol)
    x_on = {(i, s) for (i, s), v in solver.x.items() if sol.get_value(v) > 0.5}
    route, info2 = route_given_schedule(inst, x_on, time_limit, mip_gap, _log(log_path, "route"), threads)
    out.update(mip_objective_without_timing=sol.objective_value, staff_objective=sol.get_value(staff_obj),
               understaffing_hours=kpi["understaffing_hours"], wage_cost=kpi["total_wage_cost"],
               seconds=info["seconds"] + info2["seconds"])
    if route:
        out.update(route)
        out["objective"] = out["staff_objective"] + route["transport_cost"]
        out["certified_gap"] = (out["objective"] - out["lower_bound"]) / out["objective"]
    return out


def solve_sequential(inst, args, w_bus_trip=1.0, time_limit=3600, mip_gap=1e-4, log_path=None, threads=0):
    """Staff model first (with the paper's W_bus), then exact routing with timing for its schedule."""
    args.w_bus_trip = w_bus_trip
    solver = StaffSchedulingSolver(args, inst.staff)
    with redirect_stdout(io.StringIO()):
        solver.build_model()
    sol1, info1 = _solve(solver.mdl, time_limit, mip_gap, _log(log_path, "staff"), threads)
    out = {"method": "sequential", "status": info1["status"], "staff_mip_gap": info1["mip_gap"]}
    if not sol1:
        return out
    solver.solution = sol1
    kpi, bus_requests = _staff_parts(solver, sol1)
    x_on = {(i, s) for (i, s), v in solver.x.items() if sol1.get_value(v) > 0.5}
    route, info2 = route_given_schedule(inst, x_on, time_limit, mip_gap, _log(log_path, "route"), threads)
    out["x_on"] = x_on
    out.update(staff_objective=sol1.objective_value - w_bus_trip * bus_requests,  # same scale as integrated
               understaffing_hours=kpi["understaffing_hours"], wage_cost=kpi["total_wage_cost"],
               seconds=info1["seconds"] + info2["seconds"], route_mip_gap=info2["mip_gap"])
    if route:
        out.update(route)
        out["objective"] = out["staff_objective"] + route["transport_cost"]
    return out
